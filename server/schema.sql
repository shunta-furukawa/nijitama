BEGIN IMMEDIATE;
CREATE TABLE IF NOT EXISTS learner(id TEXT PRIMARY KEY,name TEXT NOT NULL,grade INTEGER NOT NULL,icon INTEGER NOT NULL,pin TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS run(id TEXT PRIMARY KEY,owner TEXT NOT NULL REFERENCES learner(id),unit TEXT NOT NULL,started INTEGER NOT NULL,ended INTEGER,targets TEXT NOT NULL,step INTEGER DEFAULT 0,hint INTEGER DEFAULT 0,since INTEGER NOT NULL,reward INTEGER DEFAULT 0);
CREATE UNIQUE INDEX IF NOT EXISTS one_active ON run(owner,unit) WHERE ended IS NULL;
CREATE TABLE IF NOT EXISTS answer(run TEXT NOT NULL REFERENCES run(id),step INTEGER NOT NULL,target INTEGER NOT NULL,value INTEGER NOT NULL,ok INTEGER NOT NULL,hint INTEGER NOT NULL,ms INTEGER NOT NULL,at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS login(token TEXT PRIMARY KEY,owner TEXT NOT NULL,expires INTEGER NOT NULL);
PRAGMA user_version=1;
COMMIT;
